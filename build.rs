//! The gateway serves everything the browser needs from inside the binary.
//! The hand-written page, styles and scripts are `include_str!`d straight
//! from `web/`; the speech library is built by Vite (`npm run build:web`)
//! into `web/dist`, where the file names carry content hashes that change
//! with every build. This script melts whatever Vite emitted into a static
//! table, so `web.rs` can serve it as easily as the rest.

use std::fs;
use std::path::Path;

const DIST: &str = "web/dist";

/// A content type for every kind of file the build emits.
fn content_type(name: &str) -> Option<&'static str> {
    if name.ends_with(".mjs") || name.ends_with(".js") {
        Some("text/javascript; charset=utf-8")
    } else if name.ends_with(".wasm") {
        Some("application/wasm")
    } else if name.ends_with(".css") {
        Some("text/css; charset=utf-8")
    } else {
        None
    }
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=vite.config.mjs");
    println!("cargo:rerun-if-changed=package.json");
    println!("cargo:rerun-if-changed=web");
    println!("cargo:rerun-if-changed=web/dist");

    let mut files: Vec<_> = fs::read_dir(DIST)
        .map(|entries| {
            entries
                .flatten()
                .filter(|entry| entry.path().is_file())
                .filter(|entry| {
                    // Build leftovers and generated maps are not worth a
                    // place in the binary; no source map is written anyway.
                    let name = entry.file_name();
                    let name = name.to_string_lossy();
                    !name.starts_with('.')
                        && content_type(&name).is_some()
                        && !name.ends_with(".map")
                })
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();
    files.sort_by_key(|entry| entry.file_name());

    let mut out = String::new();
    out.push_str("// @generated by build.rs from `web/dist` — do not edit.\n");
    out.push_str("/// What the Vite build emitted: its name under `/assets/`, its content\n");
    out.push_str("/// type, and the bytes themselves, all held inside the binary.\n");
    out.push_str("pub static BUNDLED: &[(&str, &str, &[u8])] = &[\n");
    for entry in files {
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let kind = content_type(&name).unwrap();
        out.push_str(&format!(
            "    (\"{}\", \"{}\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{}/{}\"))),\n",
            name,
            kind,
            DIST,
            name,
        ));
    }
    out.push_str("];\n");

    let binding = std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo");
    let out_dir = Path::new(&binding);
    fs::create_dir_all(out_dir).expect("the output directory can be created");
    fs::write(out_dir.join("bundled_assets.rs"), out)
        .expect("the generated asset table can be written");
}
